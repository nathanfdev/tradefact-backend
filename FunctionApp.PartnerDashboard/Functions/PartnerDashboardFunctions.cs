                model.Add(response);
            }

            return new OkObjectResult(model);
        }

        [SwaggerResponse(200, typeof(KPIResponse), Description = "OK result")]
        [SwaggerRequestBodyType(typeof(KPIRequest))]
        [FunctionName(nameof(KPI))]
        public async Task<IActionResult> KPI([HttpTrigger(AuthorizationLevel.Anonymous, "post", Route = null)]
            HttpRequest req, ILogger logger)
        {
            var request =
                    await req.GetJsonBody<KPIRequest, KPIRequestValidator>(logger).ConfigureAwait(false);

            if(!request.IsValid) {
                return request.ToBadRequest();
            }

            var kpiRequest = request.Value;

            // Dashboard
            //- Shipments requiring action are all imports without container numbers assigned
            //- Invoices due are all imports where paid flag = false

            //- Bookings is number of imports with booked flag = true
            //- Revenue summed quote price of list of all imports with booked flag = true
            //- companies is number of all companies

            var importsRequiringActionQuery = new QueryDefinition(
                                                  $"SELECT * FROM c WHERE c.partnerId = @partnerId AND NOT IS_DEFINED(c.containerNumber) AND c.type=\"Import\"")
                                    .WithParameter("@partnerId", kpiRequest.PartnerId);

            var importsRequiringAction = await _repository.GetAsync<Import>(importsRequiringActionQuery, _proxy.Imports)
                .ConfigureAwait(false);

            var invoicesDueQuery = new QueryDefinition(
                                       $"SELECT * FROM c WHERE c.partnerId = @partnerId AND c.InvoicePaid = false AND c.type=\"Import\"")
                                    .WithParameter("@partnerId", kpiRequest.PartnerId);

            var invoicesDue = await _repository.GetAsync<Import>(invoicesDueQuery, _proxy.Imports).ConfigureAwait(false);

            var bookingsQuery = new QueryDefinition(
                                    $"SELECT * FROM c WHERE c.partnerId = @partnerId AND c.status != \"PreBooking\" AND c.type=\"Import\"")
                        .WithParameter("@partnerId", kpiRequest.PartnerId);

            var bookings = await _repository.GetAsync<Import>(bookingsQuery, _proxy.Imports).ConfigureAwait(false);

            var revenueQuery = new QueryDefinition(
                                   $"SELECT * FROM c WHERE c.partnerId = @partnerId AND c.InvoicePaid = false AND c.type=\"Import\"")
                        .WithParameter("@partnerId", kpiRequest.PartnerId);

            var revenues = await _repository.GetAsync<Import>(revenueQuery, _proxy.Imports).ConfigureAwait(false);

            var companies = await _repository.GetAsync<Company>(
                                      c => c.IsActive && c.PartnerId == new Guid(request.Value.PartnerId),
                                      _proxy.Companies)
                .ConfigureAwait(false);

            var model = new KPIResponse
            {
                ImportsRequiringAction = importsRequiringAction.Count(),
                InvoicesDue = invoicesDue.Count(),
                Bookings = bookings.Count(),
                Revenue = revenues.Sum(r => r.Quotations.Sum(s=>s.TotalCost)),
                Companies = companies.Count()
            };

            return new OkObjectResult(model);
        }
