        [SwaggerResponse(200, typeof(BillingResponse[]), Description = "OK result")]
        [SwaggerRequestBodyType(typeof(BillingsRequest))]
        [FunctionName(nameof(Billing))]
        public async Task<IActionResult> Billing([HttpTrigger(AuthorizationLevel.Anonymous, "post", Route = null)]
            HttpRequest req, ILogger logger)
        {

            //  Billing
            // - Ref will need to be unique across all partners / companies and imports -generated by API
            // -Fix UX for select box for switching status

            //-Default status will be "Not Paid"
            //- Partners will set Tax rate as %, use this to calculate the tax amount in table
            //- Currency fields to be formatted in JS via Intl class

            var request =
        await req.GetJsonBody<BillingsRequest, BillingsRequestValidator>(logger).ConfigureAwait(false);

            if(!request.IsValid) {
                return request.ToBadRequest();
            }

            var items = await _repository.GetAsync<Import>(
                                  c => c.IsActive &&
                    c.Company.PartnerId ==  new Guid(request.Value.PartnerId) &&
                    (c.Quotations.Count > 0),
                                  _proxy.Imports)
                .ConfigureAwait(false);

            var model = new List<BillingResponse>();

            foreach(var item in items) {

                ImportQuotation q = item.Quotations.First();

                var response = new BillingResponse
                {
                    Amount = q.TotalCost.ToString(),
                    DateDue = q.DateDue.ToShortDateString(),
                    DateIssued = q.DateIssued.ToString(),
                    ImportName = item.Name,
                    ImportType = item.LoadType.ToString(),
                    Reference = "To be entered",
                    BillingStatus = BillingStatus.Due,
                    Tax = 10,
                    TotalPrice = q.TotalCost
                };

                model.Add(response);
            }

            return new OkObjectResult(model);
        }

