        {

            var request =
        await req.GetJsonBody<CompaniesRequest, CompaniesRequestValidator>(logger).ConfigureAwait(false);

            if(!request.IsValid) {
                return request.ToBadRequest();
            }

            // Companies
            //- Just show default address in the row expand
